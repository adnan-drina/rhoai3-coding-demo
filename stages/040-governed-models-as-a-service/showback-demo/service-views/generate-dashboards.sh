#!/usr/bin/env bash
# Generate/check platform-only Perses candidates; no server, deployment or authorization configuration.
# Usage: stages/040-governed-models-as-a-service/showback-demo/service-views/generate-dashboards.sh [--write|--check]
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
source "$REPO_ROOT/scripts/lib.sh"
MANIFEST_DIR="$REPO_ROOT/gitops/stages/040-governed-models-as-a-service/040-showback-demo/service-views"
MODE=${1:-print}
[[ $# -le 1 && ( "$MODE" == print || "$MODE" == --write || "$MODE" == --check ) ]] || {
    sed -n 's/^# Usage: //p' "$0" >&2; exit 1;
}
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
PROGRAM=$(cat <<'JQ'
def query:
  {kind:"TimeSeriesQuery",spec:{plugin:{kind:"PrometheusTimeSeriesQuery",spec:{
    datasource:{kind:"PrometheusDatasource",name:"data-science-prometheus-datasource"},
    query:("("+.metric+" @ end() and on(job, instance) (up{showback_publisher=\"selected-report\"} @ end() == 1))"),
    seriesNameFormat:.legend}}}};
def panel:
  {kind:"Panel",spec:{display:{name:.title,description:.description},plugin:{kind:"StatChart",spec:{
    calculation:"last",format:{unit:"decimal",decimalPlaces:(.decimals // 0)}}},queries:[query]}};
.[] | . as $d
| {apiVersion:"perses.dev/v1alpha2",kind:"PersesDashboard",metadata:{name:.name,namespace:"redhat-ods-monitoring",
  labels:{"app.kubernetes.io/name":.name,"app.kubernetes.io/part-of":"observability",
    "app.kubernetes.io/component":"observability","app.kubernetes.io/managed-by":"argocd","demo.rhoai.io/stage":"040"}},
  spec:{config:{display:{name:.title,description:("PLATFORM ONLY candidate. "+.description+
    " One selected immutable snapshot; current gauges, never integrate. No dashboard filter provides authorization.")},
    duration:"1h",variables:[],panels:(.panels|with_entries(.value |= panel)),
    layouts:[{kind:"Grid",spec:{display:{title:"Selected report",collapse:{open:true}},
      items:([.panels|keys[]]|to_entries|map({x:0,y:(.key*6),width:24,height:6,
        content:{"$ref":("#/spec/panels/"+.value)}}))}}]}}}
JQ
)
jq -c "$PROGRAM" "$SCRIPT_DIR/dashboard-definitions.json" > "$WORK/documents.jsonl"
status=0
while IFS= read -r document; do
    name=$(printf '%s' "$document" | jq -r '.metadata.name')
    [[ "$name" == service-view-* ]] || { log_error 'Unexpected dashboard name'; exit 1; }
    file="$name.yaml"
    {
        echo '# Generated by service-views/generate-dashboards.sh. Platform-only candidate; consumer access is not configured.'
        printf '%s' "$document" | ruby -ryaml -rjson -e 'puts YAML.dump(JSON.parse(STDIN.read))'
    } > "$WORK/$file"
    case "$MODE" in
        --write) cp "$WORK/$file" "$MANIFEST_DIR/$file" ;;
        --check) cmp -s "$WORK/$file" "$MANIFEST_DIR/$file" || { log_error "Stale $file"; status=1; } ;;
        print) cat "$WORK/$file" ;;
    esac
done < "$WORK/documents.jsonl"
exit "$status"
