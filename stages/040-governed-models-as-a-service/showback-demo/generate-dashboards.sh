#!/usr/bin/env bash
# Generate/check bounded-report and offer Perses dashboards from reviewed definitions; safe to rerun.
# Usage: stages/040-governed-models-as-a-service/showback-demo/generate-dashboards.sh [--write|--check]
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
source "$REPO_ROOT/scripts/lib.sh"
MANIFEST_DIR="$REPO_ROOT/gitops/stages/040-governed-models-as-a-service/040-showback-demo"
MODE=print
case "${1:-}" in
    --write) MODE=write ;;
    --check) MODE=check ;;
    '') ;;
    *) sed -n 's/^# Usage: //p' "$0" >&2; exit 1 ;;
esac
[[ $# -le 1 ]] || exit 1
for cmd in jq ruby; do command -v "$cmd" >/dev/null || { log_error "Missing command: $cmd"; exit 1; }; done
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
PROGRAM='
def query: {kind:"TimeSeriesQuery", spec:{plugin:{kind:"PrometheusTimeSeriesQuery", spec:.}}};
def panel: {kind:"Panel", spec:{display:{name:.title,description:.description},
    plugin:{kind:.kind,spec:.options},queries:[.queries[]|query]}};
.[] | {apiVersion:"perses.dev/v1alpha2",kind:"PersesDashboard",
  metadata:{name:.name,namespace:"redhat-ods-monitoring",labels:{
    "app.kubernetes.io/name":.name,"app.kubernetes.io/part-of":"observability",
    "app.kubernetes.io/component":"observability","app.kubernetes.io/managed-by":"argocd","demo.rhoai.io/stage":"040"}},
  spec:{config:{display:{name:.title,description:.description},duration:"1h",variables:[],
    panels:(.panels|with_entries(.value |= panel)),layouts:.layouts}}}
'
jq -c "$PROGRAM" "$SCRIPT_DIR/dashboard-definitions.json" \
    "$SCRIPT_DIR/offer-dashboard-definitions.json" > "$WORK/documents.jsonl"
status=0
while IFS= read -r document; do
    name=$(printf '%s' "$document" | jq -r '.metadata.name')
    case "$name" in
        dashboard-7-*) file=dashboard-showback-bill.yaml ;;
        dashboard-8-*) file=dashboard-showback-usage.yaml ;;
        dashboard-9-*) file=dashboard-showback-efficiency.yaml ;;
        dashboard-offer-external-model-admin) file=dashboard-offer-external.yaml ;;
        dashboard-offer-dedicated-private-admin) file=dashboard-offer-dedicated.yaml ;;
        dashboard-offer-shared-private-admin) file=dashboard-offer-shared.yaml ;;
        *) log_error "Unexpected dashboard identity"; exit 1 ;;
    esac
    {
        case "$name" in
            dashboard-offer-*)
                echo '# Generated by showback-demo/generate-dashboards.sh; edit offer-dashboard-definitions.json instead.' ;;
            *) echo '# Generated by showback-demo/generate-dashboards.sh; edit dashboard-definitions.json instead.' ;;
        esac
        printf '%s' "$document" | ruby -ryaml -rjson -e 'puts YAML.dump(JSON.parse(STDIN.read))'
    } > "$WORK/$file"
    case "$MODE" in
        write) cp "$WORK/$file" "$MANIFEST_DIR/$file" ;;
        check) cmp -s "$WORK/$file" "$MANIFEST_DIR/$file" || { log_error "Stale generated $file"; status=1; } ;;
        print) cat "$WORK/$file" ;;
    esac
done < "$WORK/documents.jsonl"
exit "$status"
