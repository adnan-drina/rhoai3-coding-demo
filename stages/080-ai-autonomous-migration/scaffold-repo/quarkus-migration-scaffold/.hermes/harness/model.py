def _utc() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _git_head(root: Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"


def _read_packages(root: Path) -> tuple[str, str]:
    yml = root / "migration.yaml"
    text = yml.read_text(encoding="utf-8", errors="replace") if yml.is_file() else ""
    lm = re.search(r"legacyPackage:\s*([\w.]+)", text)
    tm = re.search(r"targetPackage:\s*([\w.]+)", text)
    return (
        lm.group(1) if lm else "com.example.legacy",
        tm.group(1) if tm else "com.demo",
    )


def _remap_fqn(legacy_fqn: str, legacy_pkg: str, target_pkg: str) -> str:
    if legacy_fqn.startswith(legacy_pkg + ".") or legacy_fqn == legacy_pkg:
        return target_pkg + legacy_fqn[len(legacy_pkg) :]
    # Fall back: keep simple name under target root package leaf
    simple = legacy_fqn.rsplit(".", 1)[-1]
    # Preserve relative package suffix after common root when possible
    parts = legacy_fqn.split(".")
    if len(parts) >= 2:
        # Preserve trailing layer segment (model/repository/service/…) under target.
        for i, p in enumerate(parts):
            if p in ("model", "repository", "service", "rest", "util", "mapper"):
                return target_pkg + "." + ".".join(parts[i:])
    return f"{target_pkg}.{simple}"


def _path_for_fqn(fqn: str) -> str:
    return "src/main/java/" + fqn.replace(".", "/") + ".java"


def condensation_order(analysis: dict) -> tuple[list[str], dict[int, str]]:
    """Unit keys or SCC ids — never flattened multi-member SCCs (ADR-24 §2.1)."""
    imports = analysis["imports"]
    fan_in = analysis["fan_in"]
    sccs = analysis["sccs"]
    fqn_scc: dict[str, int] = {}
    for i, comp in enumerate(sccs):
        for f in comp:
            fqn_scc[f] = i
    succ: dict[int, set[int]] = {i: set() for i in range(len(sccs))}
    pred_count = {i: 0 for i in range(len(sccs))}
    for fqn, deps in imports.items():
        a = fqn_scc.get(fqn)
        if a is None:
            continue
        for d in deps:
            b = fqn_scc.get(d)
            if b is None or b == a:
                continue
            if a not in succ[b]:
                succ[b].add(a)
                pred_count[a] += 1
    ready = sorted(
        (i for i in range(len(sccs)) if pred_count[i] == 0),
        key=lambda i: (-max((fan_in[f] for f in sccs[i]), default=0), min(sccs[i])),
    )
    order: list[str] = []
    seen: set[int] = set()
    scc_id_of: dict[int, str] = {}
    multi_n = 0
    for i, comp in enumerate(sccs):
        if len(comp) > 1:
            multi_n += 1
            scc_id_of[i] = f"SCC-{multi_n}"
    while ready:
        i = ready.pop(0)
        if i in seen:
            continue
        seen.add(i)
        if len(sccs[i]) == 1:
            order.append(sccs[i][0])
        else:
            order.append(scc_id_of[i])
        for a in sorted(succ.get(i, ()), key=lambda j: (min(sccs[j]), j)):
            pred_count[a] -= 1
            if pred_count[a] == 0:
                ready.append(a)
        ready.sort(
            key=lambda j: (
                -max((fan_in[f] for f in sccs[j]), default=0),
                min(sccs[j]),
            )
        )
    for i, comp in enumerate(sccs):
        if i not in seen:
            if len(comp) == 1:
                order.append(comp[0])
            else:
                order.append(scc_id_of[i])
    return order, scc_id_of


def build_model(
    root: Path,
    legacy_root: Path,
    *,
    preserve_stories: Optional[list[dict]] = None,
) -> dict[str, Any]:
    legacy_pkg, target_pkg = _read_packages(root)
    analysis = dependency_order.analyze(str(legacy_root))
    classes = analysis["classes"]
    imports = analysis["imports"]
    fan_in = analysis["fan_in"]
    cycles = analysis["cycles"]
    order, scc_id_of = condensation_order(analysis)

    fqn_to_scc: dict[str, str] = {}
    sccs_out: list[dict] = []
    for i, comp in enumerate(analysis["sccs"]):
        if len(comp) <= 1:
            continue
        sid = scc_id_of[i]
        members = sorted(comp)
        for m in members:
            fqn_to_scc[m] = sid
        # cycle edge labels (undirected pairs among members that import each other)
        cycle_edges: list[str] = []
        for a in members:
            for b in imports.get(a, ()):
                if b in fqn_to_scc and fqn_to_scc[b] == sid and a < b:
                    cycle_edges.append(f"{a.rsplit('.',1)[-1]}<->{b.rsplit('.',1)[-1]}")
        sccs_out.append({"id": sid, "members": members, "cycles": sorted(set(cycle_edges))})

    # O-ADR24FIND: Findings IR is the only findings identity input.
    import findings_ir

    ir = findings_ir.ensure_ir(root)

    units: list[dict] = []
    for fqn, rel in sorted(classes.items()):
        # dependency-order paths are relative to legacy root (often already src/...)
        legacy_path = rel if rel.startswith("src/") else f"src/main/java/{rel}"
        # normalize when analyze walked from legacy root containing src/
        if not legacy_path.startswith("src/") and "/src/" in rel:
            legacy_path = rel[rel.index("src/") :]
        target_fqn = _remap_fqn(fqn, legacy_pkg, target_pkg)
        target_path = _path_for_fqn(target_fqn)
        staging_path = f"migration/staging/{legacy_path}"
        alt = root / "migration" / "staging" / legacy_path
        if alt.is_file():
            staging_path = str(alt.relative_to(root))
        elif (root / staging_path).is_file():
            pass

        units.append(
            {
                "key": fqn,
                "kind": "java",
                "legacy_fqn": fqn,
                "legacy_path": legacy_path,
                "target_fqn": target_fqn,
                "target_path": target_path,
                "staging_path": staging_path,
                "scc": fqn_to_scc.get(fqn),
                "depends_on": sorted(imports.get(fqn, ())),
                "fan_in": int(fan_in.get(fqn, 0)),
                "fan_out": len(imports.get(fqn, ())),
                "findings": [],
            }
        )

    # Non-java structural seeds from common migration paths (ADR-24 §2.7)
    for rel, kind in (
        ("pom.xml", "pom"),
        ("src/main/resources/application.properties", "resources"),
        ("src/main/resources/application.yml", "resources"),
    ):
        lp = legacy_root / rel
        if lp.is_file():
            key = f"coord:{rel}"
            units.append(
                {
                    "key": key,
                    "kind": kind,
                    "legacy_fqn": None,
                    "legacy_path": rel,
                    "target_fqn": None,
                    "target_path": rel,
                    "staging_path": f"migration/staging/{rel}",
                    "scc": None,
                    "depends_on": [],
                    "fan_in": 0,
                    "fan_out": 0,
                    "findings": [],
                }
            )

    # Also seed resource units referenced by IR incidents (properties etc.)
    known_lp = {u.get("legacy_path") for u in units}
    for rule in ir.get("rules") or []:
        for inc in rule.get("incidents") or []:
            lp = (inc.get("legacy_path") or "").strip()
            if not lp or lp in known_lp:
                continue
            if lp.endswith(".java"):
                continue  # java must come from class graph
            kind = findings_ir.infer_kind(lp)
            key = f"coord:{lp}"
            units.append(
                {
                    "key": key,
                    "kind": kind,
                    "legacy_fqn": None,
                    "legacy_path": lp,
                    "target_fqn": None,
                    "target_path": lp,
                    "staging_path": f"migration/staging/{lp}",
                    "scc": None,
                    "depends_on": [],
                    "fan_in": 0,
                    "fan_out": 0,
                    "findings": [],
                }
            )
            known_lp.add(lp)

    findings, units, unbound = findings_ir.bind_findings_to_units(ir, units)
    bind_reds = findings_ir.lint_bind_closed(ir, findings)
    # ADR-25 / F-unbound-zero: pristine input ⇒ unbound must be empty (no waivers)
    bind_reds.extend(findings_ir.lint_unbound_zero(unbound))

    prov = ir.get("provenance") or {}
    model: dict[str, Any] = {
        "provenance": {
            "producer": "m1",
            "source_sha": _git_head(legacy_root if (legacy_root / ".git").exists() else root),
            "findings_sha256": prov.get("source_sha256") or "",
            "findings_ir_sha256": prov.get("ir_sha256") or "",
            "legacy_package": legacy_pkg,
            "target_package": target_pkg,
            "tool_versions": {"dependency_order": "adr24", "findings_ir": "v1"},
            "generated_at": _utc(),
            "findings_unbound": unbound[:50],
            "findings_bind_reds": bind_reds,
        },
        "units": units,
        "sccs": sccs_out,
        "order": order,
        "findings": findings,
        "stories": preserve_stories if preserve_stories is not None else [],
    }
    model["_cycles_count"] = len(cycles)
    model["_bind_reds"] = bind_reds
    return model


def load(root: Path) -> dict[str, Any]:
    path = root / MODEL_REL
    if not path.is_file():
        raise FileNotFoundError(f"missing {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def save(root: Path, model: dict[str, Any]) -> Path:
    path = root / MODEL_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    # strip private keys
    out = {k: v for k, v in model.items() if not k.startswith("_")}
    path.write_text(json.dumps(out, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    return path


def unit_by_key(model: dict, key: str) -> Optional[dict]:
    for u in model.get("units") or []:
        if u.get("key") == key:
            return u
    return None


def units_for_story(model: dict, sid: str) -> list[dict]:
    for st in model.get("stories") or []:
        if st.get("id") == sid:
            keys = set(st.get("units") or [])
            return [u for u in model.get("units") or [] if u.get("key") in keys]
    return []


def scc_of(model: dict, key: str) -> Optional[dict]:
    u = unit_by_key(model, key)
    if not u or not u.get("scc"):
        return None
    for s in model.get("sccs") or []:
        if s.get("id") == u["scc"]:
            return s
    return None


def order_for_story(model: dict, sid: str) -> list[str]:
    keys = {u["key"] for u in units_for_story(model, sid)}
    if not keys:
        return list(model.get("order") or [])
    scc_ids = {
        u["scc"]
        for u in units_for_story(model, sid)
        if u.get("scc")
    }
    out: list[str] = []
    for item in model.get("order") or []:
        if item in keys or item in scc_ids:
            out.append(item)
    return out


def context_for(
    model: dict,
    sid: str,
    *,
    root: Optional[Path] = None,
    focus_task: Optional[dict] = None,
) -> str:
    """Structured M3 projection — no markdown scrape (ADR-24 G4) + ADR-38 snippets.

    O-M3SNIPPET / ADR-40: every resolvable decision cite= carries SNIPPET text
    (±2 lines) so the M3 seat must not fetch legacy files (same rule as
    context_for_m2). Generated/unresolvable cites are omitted.

    O-STAGINGOWNUNIT: when ``focus_task`` is set and its acceptance requires
    ``staging_fact``, that task's own ``unit_keys[0]`` staging path is projected
    first, then neighbours up to cap — truncation must never drop the
    acceptance target.
    """
    units = units_for_story(model, sid)
    if not units and not (model.get("stories") or []):
        # Pre-assign_stories: project by matching nothing — caller may pass scope
        units = list(model.get("units") or [])
    # Snippet resolver (optional — fixtures without legacy still project structure)
    snip_fn = None
    is_gen = None
    lr = None
    if root is not None:
        try:
            sys.path.insert(0, str(_HARNESS))
            from profile_anchors import (  # type: ignore
                is_generated_build_path,
                resolve_legacy_root,
                snippet_at_path_line,
            )

            snip_fn = snippet_at_path_line
            is_gen = is_generated_build_path
            legacy_env = os.environ.get("LEGACY_ROOT", "").strip() or None
            lr = resolve_legacy_root(root, legacy_env)
        except Exception:
            snip_fn = None
    lines = [
        "===== BEGIN DERIVED FACTS (authoritative — migration model projection) =====",
        "O-M3DERIVEDCTX: where BRIEF and DERIVED FACTS disagree, DERIVED FACTS win.",
        "O-M3SNIPPET / ADR-38: copy quotes from SNIPPET only — do NOT read /projects/legacy.",
        f"story: {sid}",
        f"units ({len(units)}):",
    ]
    n_cite = 0
    n_snip = 0
    for u in units:
        if u.get("kind") != "java":
            lines.append(
                f"  - [{u.get('kind')}] {u.get('target_path')} <- {u.get('legacy_path')}"
            )
            continue
        scc = u.get("scc") or "-"
        fids = ",".join(u.get("findings") or []) or "-"
        d = u.get("decision") if isinstance(u.get("decision"), dict) else {}
        role = (d.get("role") if d else None) or "UNDECIDED"
        cite = ""
        snip: Optional[str] = None
        if snip_fn and isinstance(d, dict):
            ev = d.get("evidence") if isinstance(d.get("evidence"), dict) else None
            if ev and ev.get("path"):
                ep = str(ev.get("path") or "").replace("\\", "/")
                if not (is_gen and is_gen(ep)):
                    snip = snip_fn(
                        root,
                        ep,
                        ev.get("line") or 0,
                        legacy_root=lr,
                        before=2,
                        after=2,
                    )
                    if snip:
                        cite = f" cite={ep}:{ev.get('line')}:{ev.get('token')}"
                        n_cite += 1
                        n_snip += 1
        lines.append(
            f"  - {u.get('target_fqn')} <- {u.get('legacy_fqn')}  role={role} "
            f"scc={scc}  findings=[{fids}]{cite}"
        )
        if snip:
            lines.append("    SNIPPET:")
            for sl in snip.splitlines():
                lines.append(f"    | {sl}")
    # convert-together batches intersecting this story
    unit_keys = {u["key"] for u in units}
    for scc in model.get("sccs") or []:
        members = set(scc.get("members") or [])
        if not members & unit_keys:
            continue
        simples = [m.rsplit(".", 1)[-1] for m in scc.get("members") or []]
        cycles = ", ".join(scc.get("cycles") or []) or "cyclic"
        lines.append(
            f"convert-together: {scc['id']} = {{{', '.join(simples)}}}  ({cycles}) — ONE task"
        )
    ord_items = order_for_story(model, sid)
    if ord_items:
        pretty = []
        for i, item in enumerate(ord_items, 1):
            if item.startswith("SCC-"):
                scc = next((s for s in model.get("sccs") or [] if s["id"] == item), None)
                if scc:
                    names = ",".join(m.rsplit(".", 1)[-1] for m in scc["members"])
                    pretty.append(f"{i} {item}{{{names}}}")
                else:
                    pretty.append(f"{i} {item}")
            else:
                pretty.append(f"{i} {item.rsplit('.', 1)[-1]}")
        lines.append("order: " + " · ".join(pretty))
    # Typed tasks already bound for this story (ADR-35 / ADR-40)
    typed = [t for t in (model.get("tasks") or []) if t.get("sid") == sid]
    if typed:
        lines.append(f"typed_tasks ({len(typed)}): harness-generated IDs — seat fills JUDGMENT only")
        for t in typed:
            lines.append(
                f"  - {t.get('id')} owns={','.join(t.get('unit_keys') or [])} "
                f"filled={bool(t.get('filled'))} acceptance_derived=yes"
            )
    # ADR-41 Move 2 / F-staging-projected: bounded staging facts for HARVEST
    # acceptance (byte-fidelity vs migration/staging) — selective, not a dump.
    harvest_paths: list[str] = []
    for u in units:
        d = u.get("decision") if isinstance(u.get("decision"), dict) else {}
        if str((d or {}).get("role") or "").upper() != "HARVEST":
            continue
        lp = str(u.get("legacy_path") or "")
        if lp:
            harvest_paths.append(lp)
    # Also cover typed owns that declare staging acceptance.
    for t in typed:
        kinds = evidence_kinds_for_acceptance(
            t.get("acceptance") or [], task_kind=str(t.get("kind") or "")
        )
        if "staging_fact" not in kinds:
            continue
        for o in t.get("owns") or []:
            # Prefer unit legacy_path when owns is target path.
            uk = (t.get("unit_keys") or [None])[0]
            uu = unit_by_key(model, uk) if uk else None
            if uu and uu.get("legacy_path"):
                harvest_paths.append(str(uu["legacy_path"]))
            elif isinstance(o, str) and o.endswith(".java"):
                harvest_paths.append(o)
    if root is not None and harvest_paths:
        # Dedupe preserving order
        seen_lp: set[str] = set()
        uniq: list[str] = []
        for p in harvest_paths:
            if p in seen_lp:
                continue
            seen_lp.add(p)
            uniq.append(p)
        # O-STAGINGOWNUNIT: own unit first when projecting for a focused seat.
        if focus_task is not None:
            kinds = evidence_kinds_for_acceptance(
                focus_task.get("acceptance") or [],
                task_kind=str(focus_task.get("kind") or ""),
            )
            if "staging_fact" in kinds:
                own: list[str] = []
                uk = (focus_task.get("unit_keys") or [None])[0]
                uu = unit_by_key(model, uk) if uk else None
                if uu and uu.get("legacy_path"):
                    own.append(str(uu["legacy_path"]))
                for o in focus_task.get("owns") or []:
                    if isinstance(o, str) and o.endswith(".java") and o not in own:
                        # Only use owns when we lack a legacy_path; otherwise
                        # owns are destination paths and do not resolve under staging.
                        if not own:
                            own.append(o)
                if own:
                    uniq = own + [p for p in uniq if p not in own]
        lines.extend(staging_fact_lines(root, uniq))
    lines.append(f"provenance: m3snip_cites={n_cite} m3snip_snippets={n_snip}")
    lines.append("===== END DERIVED FACTS =====")
    return "\n".join(lines)


def context_for_scope(
    model: dict, scope_paths: list[str], *, root: Optional[Path] = None
) -> str:
    """Projection before stories[] is bound — select units by exact legacy_path ∈ scope.

    O-ADR24BASENAME: no Path(...).name / suffix joins — scope must list full paths
    (or exact prefixes only when the scope entry itself is a directory path ending /).
    """
    scope = {p.strip().rstrip("/") for p in scope_paths if p.strip()}
    selected = []
    for u in model.get("units") or []:
        lp = (u.get("legacy_path") or "").strip()
        if not lp:
            continue
        if lp in scope:
            selected.append(u)
            continue
        # directory scopes: exact prefix with path boundary (not basename)
        for sp in scope:
            if sp.endswith(".java") or "." in Path(sp).name:
                continue
            if lp.startswith(sp.rstrip("/") + "/"):
                selected.append(u)
                break
    # Build a temporary story view
    tmp = dict(model)
    tmp["stories"] = [
        {
            "id": "SCOPE",
            "units": [u["key"] for u in selected],
            "findings": [],
            "deploy": False,
        }
    ]
    return context_for(tmp, "SCOPE", root=root).replace(
        "story: SCOPE", "story: (scope projection)"
    )


def profile_units(model: dict) -> list[dict]:
    """ADR-26 — architecture-bearing java units for M1 PROFILE coverage.

    Single SoT for the PROFILE class universe (same model as M2/M3).
    Excludes package-info.java — no architectural role to harvest/redesign.
    Identity is legacy_fqn / legacy_path (never bare basename alone).
    """
    out: list[dict] = []
    for u in model.get("units") or []:
        if u.get("kind") != "java":
            continue
        lp = (u.get("legacy_path") or "").replace("\\", "/")
        fqn = u.get("legacy_fqn") or ""
        if lp.endswith("package-info.java") or fqn.endswith("package-info"):
            continue
        out.append(u)
    return out


def context_for_profile(
    model: dict,
    *,
    root: Optional[Path] = None,
    undecided_only: bool = False,
    limit: int = 0,
    legacy: Optional[str] = None,
) -> str:
    """ADR-26 + ADR-31 — M1 PROFILE projection: checklist, not recall.

    Same DERIVED FACTS pattern as context_for (M3). PROFILE must classify
    every listed unit; rubric grades against the full universe.

    O-PROF1OF79STOP: `--undecided-only --limit N` projects a **batch** of
    units still needing a credited typed decision (null or evidence_miss),
    so seats are not asked to author 79 anchors in one overloaded prompt.

    ADR-31: each unit carries a **pre-verified anchor set**. The seat
    SELECTs evidence from that set — it does not search for line numbers.
    Apply refuses evidence ∉ the set (F-anchor-membership).
    """
    units = profile_units(model)
    batch_note = ""
    if undecided_only and root is not None:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from profile_roles import evaluate_roles  # type: ignore

        ev = evaluate_roles(Path(root), legacy=legacy)
        need = set(ev.get("undecided") or [])
        units = [
            u
            for u in units
            if (u.get("legacy_fqn") or u.get("key") or "?") in need
        ]
        batch_note = " (undecided-only batch — fill these before the rest)"
    if limit and limit > 0:
        units = units[:limit]
        batch_note = (batch_note or "") + f" (limit={limit})"
    # ADR-31 — precompute anchors once for the projected batch.
    anchor_map: dict = {}
    if root is not None:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from profile_anchors import project_text_for_units  # type: ignore

        anchor_map = project_text_for_units(Path(root), units, legacy=legacy)
    lines = [
        "===== BEGIN DERIVED FACTS (authoritative — PROFILE model projection) =====",
        "EVERY unit below needs a typed decision in",
        "migration/profile-decisions.json (or model.units[].decision):",
        "role=HARVEST|REDESIGN, rationale, evidence={path,line,token}.",
        "Evidence MUST be SELECTED from the unit's projected anchors",
        "(pre-verified path:line:token). Do NOT invent line numbers. Apply",
        "refuses evidence outside the projected set (F-anchor-membership).",
        "§7 markdown is RENDERED from those decisions — do not author role bullets.",
        "Where ANALYSIS prose and DERIVED FACTS disagree, DERIVED FACTS win.",
        "O-ADR27: source *Mapper.java interfaces ARE classify (in this list).",
        "Never class-role *MapperImpl or target/generated-sources — build-owned.",
        # Wording avoids the literal "package-info" so instruments that assert
        # the unit is absent from the projection body do not false-fail.
        f"profile-units ({len(units)} java, pkg-info rows omitted){batch_note}:",
    ]
    for u in units:
        fqn = u.get("legacy_fqn") or u.get("key") or "?"
        lp = u.get("legacy_path") or "?"
        scc = u.get("scc") or "-"
        fids = ",".join(u.get("findings") or []) or "-"
        simple = fqn.rsplit(".", 1)[-1]
        hint = "classify"
        if simple.endswith("Mapper") and "mapper" in lp.lower():
            hint = "classify-source-mapper"
        d = u.get("decision") if isinstance(u.get("decision"), dict) else None
        dstat = (
            f"decision={d.get('role')}"
            if d and d.get("role") in ("HARVEST", "REDESIGN")
            else "decision=null"
        )
        lines.append(
            f"  - {fqn}  path={lp}  simple={simple}  scc={scc}  "
            f"findings=[{fids}]  hint={hint}  {dstat}"
        )
        if root is not None:
            from profile_anchors import format_anchors_block  # type: ignore

            lines.extend(format_anchors_block(anchor_map.get(fqn) or []))
    # non-java demand still visible for modernization surface
    other = [
        u
        for u in model.get("units") or []
        if u.get("kind") != "java" and (u.get("findings") or [])
    ]
    if other:
        lines.append(f"non-java demand units ({len(other)}) — cite in §5, not §7 class-roles:")
        for u in other:
            fids = ",".join(u.get("findings") or []) or "-"
            lines.append(
                f"  - [{u.get('kind')}] {u.get('legacy_path')}  findings=[{fids}]"
            )
    lines.append("===== END DERIVED FACTS =====")
    return "\n".join(lines)


