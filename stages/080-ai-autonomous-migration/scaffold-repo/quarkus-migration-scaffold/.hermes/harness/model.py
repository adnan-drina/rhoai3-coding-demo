def main() -> int:
    ap = argparse.ArgumentParser(description="ADR-24 migration model")
    # Parent so `--root` works before or after the subcommand.
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--root", default=".")
    sub = ap.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("emit", parents=[common])
    e.add_argument("--legacy", default="/projects/legacy")
    e.add_argument("--fresh-stories", action="store_true")
    e.set_defaults(func=cmd_emit)

    a = sub.add_parser("assign-stories", parents=[common])
    a.set_defaults(func=cmd_assign)

