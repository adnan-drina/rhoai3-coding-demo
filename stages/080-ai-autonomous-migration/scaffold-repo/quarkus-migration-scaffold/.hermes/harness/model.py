def _decision_complete_local(d: Optional[dict]) -> bool:
    if not isinstance(d, dict):
        return False
    role = str(d.get("role") or "").upper()
    if role not in ("HARVEST", "REDESIGN"):
        return False
    ev = d.get("evidence") if isinstance(d.get("evidence"), dict) else None
    if not ev:
        return False
    return bool(ev.get("path") and ev.get("line") is not None and ev.get("token"))


def model_has_typed_decisions(model: dict) -> bool:
    """ADR-34: typed profile decisions present → stories[] from model, not roadmap."""
    for u in profile_units(model):
        d = u.get("decision") if isinstance(u.get("decision"), dict) else None
        if _decision_complete_local(d):
            return True
    return False


def _layer_for_legacy_path(path: str) -> str:
    """Packaging label only (not membership SoT) — mirrors m2-compose.layer_for_path.

    O-M2DTOSURFACE (W4-759): OpenAPI/transfer ``/dto/`` and MapStruct ``/mapper/``
    package with the REST surface story (not remaining/other) so stories[] matches
    DtoHarvest / mapper ownership under ADR-34.
    """
    p = (path or "").replace("\\", "/").lower()
    if p.endswith("pom.xml") or "/pom.xml" in p or p.endswith(".xml") and "src/" not in p:
        return "platform"
    if "/model/" in p or "/domain/" in p:
        return "model"
    if "/repository/" in p or "/repo/" in p or "/dao/" in p:
        return "repository"
    if "/service/" in p:
        return "service"
    if (
        "/rest/" in p
        or "/web/" in p
        or "/controller/" in p
        or "/security/" in p
        or "/dto/" in p
        or "/mapper/" in p
    ):
        return "surface"
    if "/config/" in p or "/configuration/" in p:
        return "surface"
    return "other"


_LAYER_ORDER = (
    "platform",
    "model",
    "repository",
    "service",
    "surface",
    "other",
)
_LAYER_SLUG = {
    "platform": "platform-bom",
    "model": "domain-model",
    "repository": "repository-layer",
    "service": "service-layer",
    "surface": "rest-surface",
    "other": "remaining",
}


def _story_index_map(stories: list[dict]) -> dict[str, int]:
    return {str(s.get("id") or ""): i for i, s in enumerate(stories) if s.get("id")}


def _unit_story_map(stories: list[dict]) -> dict[str, str]:
    out: dict[str, str] = {}
    for st in stories:
        sid = str(st.get("id") or "")
        for k in st.get("units") or []:
            if k and sid:
                out[str(k)] = sid
    return out


def _scc_cohort(key: str, scc_members: dict[str, list[str]]) -> list[str]:
    for mem in scc_members.values():
        if key in mem:
            return list(mem)
    return [key]


def forward_edges(model: dict) -> list[tuple[str, str, str, str]]:
    """F-story-order / O-STORYORDER — (A, B, story_A, story_B) where A→B and B after A.

    Criterion (W4-547): if unit A depends on unit B, B's story must not come
    after A's. ``forward_edges == 0``.
    """
    stories = list(model.get("stories") or [])
    idx = _story_index_map(stories)
    claimed = _unit_story_map(stories)
    units = {
        u["key"]: u
        for u in (model.get("units") or [])
        if u.get("key") and u.get("kind") == "java"
    }
    edges: list[tuple[str, str, str, str]] = []
    for a_key, a_u in units.items():
        sa = claimed.get(a_key)
        if not sa or sa not in idx:
            continue
        for b_key in a_u.get("depends_on") or []:
            if b_key not in units:
                continue
            sb = claimed.get(b_key)
            if not sb or sb not in idx:
                continue
            if idx[sb] > idx[sa]:
                edges.append((a_key, b_key, sa, sb))
    return edges


def lint_story_order(model: dict) -> list[str]:
    """Refuse when forward_edges > 0 (F-story-order)."""
    edges = forward_edges(model)
    if not edges:
        return []
    sample = ", ".join(
        f"{sa}:{a.split('.')[-1]}→{sb}:{b.split('.')[-1]}"
        for a, b, sa, sb in edges[:6]
    )
    return [
        f"F-story-order RED: forward_edges={len(edges)} "
        f"(dep scheduled after dependent): {sample}"
    ]


def schedule_ranks(
    units: dict[str, dict],
    unit_to_layer: dict[str, str],
    scc_members: dict[str, list[str]],
) -> dict[str, int]:
    """O-STORYORDER / graph-derived ranks — F-story-order by construction.

    ``desired_rank`` comes from packaging layer (label, not membership SoT).
    Dependency closure then pulls every dep to ``min(rank(dep), rank(dependent))``
    (SCC-atomic) so ``forward_edges == 0`` before stories are materialised.
    No post-hoc move across an already-wrong partition.
    """
    layer_rank = {lay: i for i, lay in enumerate(_LAYER_ORDER)}
    rank: dict[str, int] = {
        k: layer_rank.get(unit_to_layer.get(k, "other"), len(_LAYER_ORDER) - 1)
        for k in units
    }
    # SCC-atomic: whole cohort shares min desired rank.
    for mem in scc_members.values():
        if not mem:
            continue
        r = min(rank[m] for m in mem if m in rank)
        for m in mem:
            if m in rank:
                rank[m] = r
    # Pull deps earlier until stable (by-construction schedule).
    for _ in range(max(8, len(units) + 2)):
        changed = False
        for a_key, a_u in units.items():
            ra = rank.get(a_key)
            if ra is None:
                continue
            for b_key in a_u.get("depends_on") or []:
                if b_key not in rank:
                    continue
                cohort = _scc_cohort(b_key, scc_members)
                rb = min(rank[m] for m in cohort if m in rank)
                if rb > ra:
                    for m in cohort:
                        if m in rank and rank[m] > ra:
                            rank[m] = ra
                            changed = True
        if not changed:
            break
    return rank


def stories_from_ranks(
    units: dict[str, dict],
    unit_to_layer: dict[str, str],
    ranks: dict[str, int],
) -> list[dict]:
    """Materialise S01..Sn from schedule ranks; slug/layer are labels only."""
    by_rank: dict[int, list[str]] = {}
    for k, r in ranks.items():
        by_rank.setdefault(r, []).append(k)
    stories: list[dict] = []
    for i, r in enumerate(sorted(by_rank)):
        keys = sorted(by_rank[r])
        # Dominant layer among members — packaging label, not SoT.
        lay_counts: dict[str, int] = {}
        for k in keys:
            lay = unit_to_layer.get(k, "other")
            lay_counts[lay] = lay_counts.get(lay, 0) + 1
        lay = sorted(
            lay_counts,
            key=lambda L: (-lay_counts[L], _LAYER_ORDER.index(L) if L in _LAYER_ORDER else 99),
        )[0]
        stories.append(
            {
                "id": f"S{i + 1:02d}",
                "slug": _LAYER_SLUG.get(lay, lay),
                "units": keys,
                "findings": [],  # filled below — K1 partition (earliest story wins)
                "deploy": False,
                "layer": lay,
                "schedule_rank": r,
            }
        )
    if stories:
        for st in stories[:-1]:
            st["deploy"] = False
        stories[-1]["deploy"] = True
        # F-story-order companion: a finding id owned by multiple units across
        # stories must land in exactly one story (earliest schedule_rank).
        claimed: set[str] = set()
        for st in stories:
            fids: list[str] = []
            for k in st.get("units") or []:
                for fid in (units.get(k) or {}).get("findings") or []:
                    if fid in claimed:
                        continue
                    claimed.add(fid)
                    fids.append(fid)
            st["findings"] = sorted(set(fids))
    return stories


def attach_companion_units(model: dict, stories: list[dict]) -> int:
    """ADR-39 — attach package-info + coord units to stories (membership SoT).

    ``profile_units`` deliberately excludes package-info (no PROFILE harvest
    role). Those units — and pom/resources coords — still need a story owner
    so ``story_scope`` / O-SCOPEVIEW / O-SCOPECOVER stay honest. Attachment
    rules (migration-general):

    - ``package-info.java`` → story owning the most units in the same package
      directory (parent path majority); else last/deploy story.
    - ``kind in {pom, resources}`` / ``coord:*`` → story whose ``layer`` label
      matches ``_layer_for_legacy_path``; else last/deploy story.

    Never reassigns a key already in ``stories[].units``. Returns attach count.
    """
    if not stories:
        return 0
    units_by_key: dict[str, dict] = {}
    for u in model.get("units") or []:
        if not isinstance(u, dict):
            continue
        key = str(u.get("key") or "").strip()
        if key:
            units_by_key[key] = u
    claimed = set(_unit_story_map(stories))
    story_by_id = {str(st.get("id") or ""): st for st in stories if st.get("id")}
    dir_scores: dict[str, dict[str, int]] = {}
    for st in stories:
        sid = str(st.get("id") or "")
        if not sid:
            continue
        for k in st.get("units") or []:
            u = units_by_key.get(k) or {}
            lp = str(u.get("legacy_path") or "").replace("\\", "/").strip()
            if not lp:
                continue
            d = str(Path(lp).parent).replace("\\", "/")
            bucket = dir_scores.setdefault(d, {})
            bucket[sid] = bucket.get(sid, 0) + 1
    last = stories[-1]
    last_id = str(last.get("id") or "")
    n = 0

    def _append(sid: str, key: str) -> None:
        nonlocal n
        st = story_by_id.get(sid)
        if st is None or key in claimed:
            return
        units_list = st.setdefault("units", [])
        if key not in units_list:
            units_list.append(key)
        claimed.add(key)
        n += 1

    for key, u in units_by_key.items():
        if key in claimed:
            continue
        lp = str(u.get("legacy_path") or "").replace("\\", "/").strip()
        fqn = str(u.get("legacy_fqn") or "")
        kind = str(u.get("kind") or "")
        is_pkginfo = lp.endswith("package-info.java") or fqn.endswith("package-info")
        if is_pkginfo:
            d = str(Path(lp).parent).replace("\\", "/") if lp else ""
            scores = dir_scores.get(d) or {}
            if scores:
                sid = sorted(scores, key=lambda s: (-scores[s], s))[0]
            else:
                sid = last_id
            _append(sid, key)
            continue
        if kind in ("pom", "resources") or key.startswith("coord:"):
            lay = _layer_for_legacy_path(lp)
            dest = next(
                (st for st in stories if (st.get("layer") or "") == lay),
                None,
            )
            sid = str((dest or last).get("id") or "")
            _append(sid, key)
    return n


def assign_stories_from_model(root: Path, model: Optional[dict] = None) -> dict:
    """ADR-34 + O-STORYORDER — graph-derived schedule from deps + layer labels.

    Membership SoT: depends_on closure over desired layer ranks (SCC-atomic).
    Layers/slugs are packaging labels only — not a catch-all decided by exclusion.
    **Never reads roadmap.md** (roadmap is a rendered view only).
    """
    model = model or load(root)
    units = {
        u["key"]: u
        for u in profile_units(model)
        if u.get("key") and u.get("kind") == "java"
    }
    scc_members: dict[str, list[str]] = {}
    for scc in model.get("sccs") or []:
        sid = scc.get("id") or ""
        mem = [m for m in (scc.get("members") or []) if m in units]
        if sid and mem:
            scc_members[sid] = mem

    def _unit_layer(key: str) -> str:
        u = units.get(key) or {}
        return _layer_for_legacy_path(u.get("legacy_path") or "")

    def _scc_layer(members: list[str]) -> str:
        layers = [_unit_layer(m) for m in members]
        if not layers:
            return "other"
        return sorted(layers, key=lambda lay: _LAYER_ORDER.index(lay))[0]

    unit_to_layer: dict[str, str] = {}
    for item in model.get("order") or []:
        if item in scc_members:
            lay = _scc_layer(scc_members[item])
            for m in scc_members[item]:
                unit_to_layer[m] = lay
        elif item in units:
            unit_to_layer[item] = _unit_layer(item)
    for key in units:
        unit_to_layer.setdefault(key, _unit_layer(key))

    # F-scc-atomic: every SCC member shares one packaging layer label.
    for sid, mem in scc_members.items():
        lays = {unit_to_layer.get(m) for m in mem}
        if len(lays) > 1:
            raise SystemExit(
                f"O-ADR34 assign_stories RED: {sid} split across layers {sorted(lays)} "
                f"(F-scc-atomic)"
            )

    ranks = schedule_ranks(units, unit_to_layer, scc_members)
    stories = stories_from_ranks(units, unit_to_layer, ranks)
    claimed = _unit_story_map(stories)

    all_java = set(units)
    orphans = sorted(all_java - set(claimed))
    if orphans:
        raise SystemExit(
            f"O-ADR34 assign_stories RED: {len(orphans)} unassigned java unit(s) "
            f"(F-story-partition): {orphans[:8]}"
        )

    # ADR-39 companions — package-info + coords enter membership after partition.
    n_comp = attach_companion_units(model, stories)

    model["stories"] = stories
    bad = lint_story_order(model)
    if bad:
        raise SystemExit(f"O-STORYORDER assign_stories RED: {bad[0]}")
    prov = model.setdefault("provenance", {})
    prov["stories_assigned_at"] = _utc()
    prov["stories_source"] = "model-partition"  # F-story-rendered witness
    prov["stories_schedule"] = "graph-derived-ranks"  # O-STORYORDER architecture
    if n_comp:
        prov["companion_units_attached"] = n_comp
    save(root, model)
    claimed_n = len(_unit_story_map(stories))
    # O-LOGNOBANK: human summary on stdout; bank token on stderr only.
    print(
        f"story assignment: stories={len(stories)} units={claimed_n} "
        f"companions={n_comp} source=model-partition schedule=graph-derived "
        f"forward_edges=0"
    )
    print(
        f"O-ADR34: assign_stories_from_model stories={len(stories)} "
        f"units={claimed_n} companions={n_comp} source=model-partition "
        f"schedule=graph-derived forward_edges=0 (F-story-order)",
        file=sys.stderr,
    )
    return model


def assign_stories_from_roadmap(root: Path, model: Optional[dict] = None) -> dict:
    """Legacy / fixture path — parse roadmap.md when typed decisions are absent."""
    model = model or load(root)
    roadmap = root / "migration" / "roadmap.md"
    if not roadmap.is_file():
        raise FileNotFoundError("migration/roadmap.md required for assign_stories")
    text = roadmap.read_text(encoding="utf-8", errors="replace")
    blocks = re.split(r"(?m)^##\s+(S\d+)\b", text)
    # blocks: [pre, S01, body1, S02, body2, ...]
    stories: list[dict] = []
    claimed: dict[str, str] = {}
    units_by_legacy_path = {
        u.get("legacy_path"): u for u in model.get("units") or [] if u.get("legacy_path")
    }
    units_by_key = {u["key"]: u for u in model.get("units") or []}

    for i in range(1, len(blocks), 2):
        sid = blocks[i]
        body = blocks[i + 1] if i + 1 < len(blocks) else ""
        sm = re.search(r"(?im)^-\s*slug:\s*(\S+)", body)
        slug = sm.group(1) if sm else sid
        dm = re.search(r"(?im)^-\s*deploy:\s*(true|false)", body)
        deploy = bool(dm and dm.group(1).lower() == "true")
        scm = re.search(r"(?im)^-\s*scope:\s*(.+)$", body)
        scope_raw = scm.group(1).strip() if scm else ""
        paths = [p.strip() for p in re.split(r"[\s,]+", scope_raw) if p.strip()]
        unit_keys: list[str] = []
        for p in paths:
            # O-ADR24BASENAME: exact legacy_path / coord key only — no basename join.
            u = units_by_legacy_path.get(p)
            if u is None:
                key = f"coord:{p}"
                if key in units_by_key:
                    u = units_by_key[key]
            if u is None:
                continue
            k = u["key"]
            if k in claimed and claimed[k] != sid:
                raise SystemExit(
                    f"O-ADR24 assign_stories RED: unit {k} dual-owned by "
                    f"{claimed[k]} and {sid}"
                )
            claimed[k] = sid
            if k not in unit_keys:
                unit_keys.append(k)

        # SCC-indivisible at M2: claiming any member claims the whole SCC into
        # this story; refuse only when members are already claimed elsewhere (F7).
        for scc in model.get("sccs") or []:
            members = scc.get("members") or []
            hit = [m for m in members if m in unit_keys]
            if not hit:
                continue
            for m in members:
                if m in claimed and claimed[m] != sid:
                    raise SystemExit(
                        f"O-ADR24 assign_stories RED: {scc['id']} spans "
                        f"{claimed[m]} and {sid} (F7)"
                    )
                claimed[m] = sid
                if m not in unit_keys:
                    unit_keys.append(m)

        fids: list[str] = []
        for k in unit_keys:
            fids.extend(units_by_key.get(k, {}).get("findings") or [])
        stories.append(
            {
                "id": sid,
                "slug": slug,
                "units": unit_keys,
                "findings": sorted(set(fids)),
                "deploy": deploy,
            }
        )

    # Total + disjoint: every java unit assigned exactly once.
    all_java = {
        u["key"] for u in model.get("units") or [] if u.get("kind") == "java"
    }
    orphans = sorted(all_java - set(claimed))
    if orphans:
        raise SystemExit(
            f"O-ADR24 assign_stories RED: {len(orphans)} unassigned java unit(s) "
            f"(total invariant): {orphans[:8]}"
        )

    # O-STORYORDER: no post-hoc repair. Roadmap partition must already satisfy
    # F-story-order; typed path uses schedule_ranks (by construction).
    model["stories"] = stories
    bad = lint_story_order(model)
    if bad:
        raise SystemExit(
            f"O-STORYORDER assign_stories RED (roadmap path refuses repair): {bad[0]}"
        )
    prov = model.setdefault("provenance", {})
    prov["stories_assigned_at"] = _utc()
    prov["stories_source"] = "roadmap-parse"
    save(root, model)
    return model


