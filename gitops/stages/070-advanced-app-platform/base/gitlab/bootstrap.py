"""Configure generated GitLab secrets without a NooBaa administrator credential."""
import base64
import datetime
import hashlib
import hmac
import json
import re
import secrets
import subprocess
import time
import urllib.request
from pathlib import Path
from urllib.parse import urlsplit

NAMESPACE = 'gitlab-system'
FEATURES = ('lfs', 'artifacts', 'uploads', 'packages', 'backups', 'backup-tmp')


def oc(*args, document=None):
    result = subprocess.run(['oc', *args], input=None if document is None else json.dumps(document),
                            text=True, capture_output=True, check=True)
    return json.loads(result.stdout) if result.stdout.strip().startswith('{') else result.stdout.strip()


def optional(kind, name):
    try:
        return oc('get', kind, name, '-n', NAMESPACE, '-o', 'json')
    except subprocess.CalledProcessError as error:
        if '(NotFound)' not in error.stderr:
            raise
        return None


def secret(name, data, derived=False):
    # Existing passwords are never regenerated by a reconcile or restart.
    existing = optional('secret', name)
    if existing:
        if derived:
            return oc('patch', 'secret', name, '-n', NAMESPACE, '--type=merge',
                      '-p', json.dumps({'stringData': data}))
        return existing
    return oc('create', '-f', '-', '-o', 'json', document={
        'apiVersion': 'v1', 'kind': 'Secret', 'metadata': {'name': name, 'namespace': NAMESPACE},
        'type': 'Opaque', 'stringData': data})


def configmap(name, data):
    if optional('configmap', name):
        return oc('patch', 'configmap', name, '-n', NAMESPACE, '--type=merge',
                  '-p', json.dumps({'data': data}))
    return oc('create', '-f', '-', '-o', 'json', document={
        'apiVersion': 'v1', 'kind': 'ConfigMap', 'metadata': {'name': name, 'namespace': NAMESPACE},
        'data': data})


def upgrade_action(target, previous, initial, database_exists):
    """Never infer the installed version from a newly applied chart-info manifest."""
    if previous is not None:
        if set(previous) != {'gitlabVersion', 'gitlabChartVersion'} or any(
                not isinstance(value, str) or not re.fullmatch(r'v?\d+\.\d+\.\d+', value) for value in previous.values()):
            raise RuntimeError('Malformed GitLab release receipt; inspect it before upgrading')
        for key, value in previous.items():
            old = tuple(map(int, value.lstrip('v').split('.')))
            new = tuple(map(int, target[key].lstrip('v').split('.')))
            if new < old:
                raise RuntimeError('GitLab downgrade requires a supported restore, not a pin rollback')
        return 'check'
    if initial is not None:
        if initial != target:
            raise RuntimeError('Incomplete GitLab installation belongs to another release; reviewed recovery required')
        return 'resume'
    if database_exists:
        raise RuntimeError('GitLab database exists without a release receipt; inspect it before upgrading')
    return 'initialize'


def check_upgrade(target):
    previous = optional('configmap', 'gitlab-gitlab-chart-info')
    initial = optional('configmap', 'gitlab-initial-release')
    action = upgrade_action(target, previous.get('data', {}) if previous is not None else None,
                            initial.get('data', {}) if initial is not None else None,
                            optional('pvc', 'gitlab-postgresql-data') is not None)
    if action == 'check':
        subprocess.run(['/bin/sh', '/scripts/runcheck'], check=True)
    elif action == 'initialize':
        configmap('gitlab-initial-release', target)
    print('GitLab upgrade precondition passed: ' + action)


def runtime_data(templates, host, domain, claims):
    result = {}
    replacements = {'gitlab.example.invalid': host, 'apps.example.invalid': domain}
    replacements.update({'pending-' + feature: value[0] for feature, value in claims.items()})
    for name, data in templates.items():
        result[name] = {}
        for key, text in data.items():
            for marker, value in sorted(replacements.items(), key=lambda item: -len(item[0])):
                text = text.replace(marker, value)
            if 'pending-' in text or 'example.invalid' in text:
                raise RuntimeError('Unresolved GitLab runtime template: ' + name + '/' + key)
            result[name][key] = text
    return result


def put_temp_policy(endpoint, bucket, access, key, backup_bucket):
    """Grant only the backup OBC account access to the separate temporary bucket."""
    body = json.dumps({'Version': '2012-10-17', 'Statement': [{
        'Effect': 'Allow', 'Principal': {'AWS': ['obc-account.' + backup_bucket + '@noobaa.io']},
        'Action': ['s3:ListBucket', 's3:GetObject', 's3:PutObject', 's3:DeleteObject',
                   's3:AbortMultipartUpload', 's3:ListBucketMultipartUploads', 's3:ListMultipartUploadParts'],
        'Resource': ['arn:aws:s3:::' + bucket, 'arn:aws:s3:::' + bucket + '/*']}]}).encode()
    now = datetime.datetime.now(datetime.timezone.utc)
    day, stamp = now.strftime('%Y%m%d'), now.strftime('%Y%m%dT%H%M%SZ')
    host = urlsplit(endpoint).netloc
    path = '/' + bucket
    digest = hashlib.sha256(body).hexdigest()
    names = 'host;x-amz-content-sha256;x-amz-date'
    canonical = f'PUT\n{path}\npolicy=\nhost:{host}\nx-amz-content-sha256:{digest}\nx-amz-date:{stamp}\n\n{names}\n{digest}'
    scope = f'{day}/us-east-1/s3/aws4_request'
    signing_key = ('AWS4' + key).encode()
    for part in (day, 'us-east-1', 's3', 'aws4_request'):
        signing_key = hmac.new(signing_key, part.encode(), hashlib.sha256).digest()
    signature = hmac.new(signing_key, f'AWS4-HMAC-SHA256\n{stamp}\n{scope}\n{hashlib.sha256(canonical.encode()).hexdigest()}'.encode(), hashlib.sha256).hexdigest()
    headers = {'x-amz-content-sha256': digest, 'x-amz-date': stamp,
               'Authorization': f'AWS4-HMAC-SHA256 Credential={access}/{scope}, SignedHeaders={names}, Signature={signature}'}
    with urllib.request.urlopen(urllib.request.Request(endpoint + path + '?policy=', body, headers, method='PUT'), timeout=30) as response:
        if response.status != 200 and response.status != 204:
            raise RuntimeError('NooBaa rejected the scoped backup policy')


def main():
    import sys
    phase = sys.argv[1] if len(sys.argv) > 1 else 'prepare'
    target = json.loads(Path('/runtime/release.json').read_text())
    if phase == 'check-upgrade':
        check_upgrade(target)
        return
    if phase == 'record-version':
        for name in ('gitlab-webservice-default', 'gitlab-sidekiq-all-in-1-v2', 'gitlab-toolbox'):
            deployment = oc('get', 'deployment', name, '-n', NAMESPACE, '-o', 'json')
            status = deployment.get('status', {})
            if status.get('observedGeneration', 0) < deployment['metadata']['generation'] or status.get('availableReplicas', 0) < 1:
                raise RuntimeError('GitLab is not ready; installed version will not be recorded')
        configmap('gitlab-gitlab-chart-info', target)
        print('GitLab migrated release and readiness recorded')
        return
    if phase != 'prepare':
        raise ValueError('Unknown GitLab bootstrap phase')
    subprocess.run(['python3', '/bootstrap/bootstrap-oidc.py'], check=True)
    secret('gitlab-database', {'username': 'gitlab', 'database': 'gitlabhq_production', 'password': secrets.token_urlsafe(32)})
    secret('gitlab-cache', {'password': secrets.token_urlsafe(32)})
    secret('gitlab-initial-root', {'password': secrets.token_urlsafe(32)})
    claims = {}
    for feature in FEATURES:
        for attempt in range(90):
            obc = oc('get', 'obc', 'gitlab-' + feature, '-n', NAMESPACE, '-o', 'json')
            if obc.get('status', {}).get('phase') == 'Bound':
                break
            time.sleep(5)
        else:
            raise RuntimeError('GitLab bucket did not bind: ' + feature)
        config = oc('get', 'configmap', 'gitlab-' + feature, '-n', NAMESPACE, '-o', 'json')['data']
        credentials = oc('get', 'secret', 'gitlab-' + feature, '-n', NAMESPACE, '-o', 'json')['data']
        decode = lambda name: base64.b64decode(credentials[name]).decode()
        claims[feature] = (config['BUCKET_NAME'], decode('AWS_ACCESS_KEY_ID'), decode('AWS_SECRET_ACCESS_KEY'))
    host = oc('get', 'route', 's3', '-n', 'openshift-storage', '-o', 'json')['spec']['host']
    endpoint = 'https://' + host
    for feature in FEATURES[:4]:
        bucket, access, key = claims[feature]
        secret('gitlab-storage-' + feature, {'connection': json.dumps({
            'provider': 'AWS', 'region': 'us-east-1', 'aws_access_key_id': access,
            'aws_secret_access_key': key, 'endpoint': endpoint, 'path_style': True,
            'enable_signature_v4_streaming': False})}, derived=True)
    bucket, access, key = claims['backup-tmp']
    put_temp_policy(endpoint, bucket, access, key, claims['backups'][0])
    _, access, key = claims['backups']
    secret('gitlab-storage-backups', {'config': f'[default]\naccess_key = {access}\nsecret_key = {key}\nhost_base = {host}\nhost_bucket = {host}\nuse_https = True\nsignature_v2 = False\nbucket_location = us-east-1\n'}, derived=True)
    domain = oc('get', 'ingress.config.openshift.io', 'cluster', '-o', 'json')['spec']['domain']
    route = oc('get', 'route', 'gitlab', '-n', NAMESPACE, '-o', 'json')
    route_host = route.get('spec', {}).get('host')
    if not route_host or not route_host.endswith('.' + domain):
        raise RuntimeError('GitLab Route has no host in the expected ingress domain')
    templates = json.loads(Path('/runtime/templates.json').read_text())
    for name, data in runtime_data(templates, route_host, domain, claims).items():
        configmap(name, data)
    print('GitLab native manifests configured from the Route and six scoped claims')


if __name__ == '__main__':
    main()
